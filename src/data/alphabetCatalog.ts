export const ALPHABET_BATCHES: Batch[] = ALPHABET_MEDICINES.map((med, idx) => {
  const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
  const char1 = letters[idx % 26];
  const char2 = letters[(idx * 3 + 7) % 26];
  const batchNum = `B${100 + (idx % 900)}-${char1}${char2}`;

  // Distribute realistic expiry & quantity:
  // - Mostly healthy stock
  // - A few low stock (< 20)
  // - A few expiring soon (in 45-75 days)
  let qty = 60 + ((idx * 17) % 180);
  let expiryDate = '2027-11-30';

  if (idx % 15 === 3) {
    qty = 8; // Low stock alert trigger
    expiryDate = '2027-04-30';
  } else if (idx % 12 === 2) {
    qty = 45;
    expiryDate = '2026-11-15'; // Expiring soon
  } else if (idx % 8 === 0) {
    expiryDate = '2028-06-30';
  }

  const supId = med.preferredSupplierId || (idx % 2 === 0 ? 'sup-1' : 'sup-2');
  const supName =
    supId === 'sup-1'
      ? 'Sun Pharmaceutical Distributors Ltd.'
      : supId === 'sup-2'
      ? 'Apollo Healthcare Wholesale Logistics'
      : 'Cipla Med-Wholesale C&F Logistics';

  return {
    id: `batch-${med.id}-init`,
    medicineId: med.id,
    batchNumber: batchNum,
    mfgDate: '2025-05',
    expiryDate,
    quantity: qty,
    initialQuantity: Math.max(qty, 100),
    purchasePrice: med.purchasePrice,
    mrp: med.mrp,
    supplierId: supId,
    supplierName: supName,
    invoiceNumber: `INV-2026-${3100 + idx}`,
    receivedDate: '2026-09-12',
  };
});
